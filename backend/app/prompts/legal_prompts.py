def get_prompt(name: str) -> str:
    """Get a prompt template by name.

    Args:
        name: The prompt name (e.g., 'legal_consult_system', 'intent_classification').

    Returns:
        The prompt template string.

    Raises:
        KeyError: If the prompt name is not found.
    """
    if name not in _PROMPT_REGISTRY:
        raise KeyError(
            f"Unknown prompt '{name}'. Available prompts: {list(_PROMPT_REGISTRY.keys())}"
        )
    return _PROMPT_REGISTRY[name]


def list_prompts() -> list[str]:
    """List all available prompt names."""
    return list(_PROMPT_REGISTRY.keys())