def generate_expanded_seed() -> None:
    """生成扩充版种子数据 JSON 文件。"""
    # 合并种子数据和补充数据
    all_articles = list(ARTICLES_DATA) + EXTRA_ARTICLES
    all_cases = list(COURT_CASES_DATA) + EXTRA_CASES
    all_laws = list(LAWS_DATA)
    all_concepts = list(LEGAL_CONCEPTS_DATA)

    # 生成输出
    output = {
        "laws": all_laws,
        "articles": all_articles,
        "cases": all_cases,
        "concepts": all_concepts,
    }

    # 写入文件
    output_dir = PROJECT_ROOT / "data"
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "expanded_legal_seed.json"

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)

    # 打印统计
    print("=" * 60)
    print("  扩充版法律知识库种子数据 — 生成完成")
    print("=" * 60)
    print(f"\n  输出文件: {output_path}")
    print(f"\n  数据统计:")
    print(f"    法律(Laws)      : {len(all_laws)} 部")
    print(f"    法条(Articles)  : {len(all_articles)} 条")
    print(f"    案例(Cases)     : {len(all_cases)} 条")
    print(f"    概念(Concepts)  : {len(all_concepts)} 条")
    print(f"    总计            : {len(all_laws) + len(all_articles) + len(all_cases) + len(all_concepts)} 条")
    print(f"\n  导入命令:")
    print(f"    cd backend")
    print(f"    python -m app.rag.batch_import --source json --file data/expanded_legal_seed.json")
    print("=" * 60)


if __name__ == "__main__":
    generate_expanded_seed()
