def _count_lines(path: str, env_override: str | None = None) -> int:
    """Count newline-delimited records.

    The synthetic corpus is ~16 GB and is deliberately *not* mounted into the
    application container, so callers can pass an ``env_override`` variable
    holding a count measured on the host instead.
    """
    if env_override:
        raw = os.environ.get(env_override, "").strip()
        if raw:
            try:
                return int(raw)
            except ValueError:
                pass
    if not os.path.exists(path):
        return -1
    n = 0
    with open(path, "rb") as f:
        for _ in f:
            n += 1
    return n


async def milvus_counts() -> dict[str, int]:
    try:
        from pymilvus import Collection, connections, utility
        connections.connect(host=os.environ.get("MILVUS_HOST", "milvus"),
                            port=os.environ.get("MILVUS_PORT", "19530"))
        out = {}
        for name in utility.list_collections():
            try:
                col = Collection(name)
                col.load()
                out[name] = col.num_entities
            except Exception:  # noqa: BLE001
                out[name] = -1
        return out
    except Exception:  # noqa: BLE001
        return {}


async def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dsn", default=DEFAULT_DSN)
    ap.add_argument("--json", dest="json_out", default=None)
    args = ap.parse_args()

    conn = await asyncpg.connect(args.dsn)
    try:
        await conn.execute(SCHEMA_SQL)
        sources = await collect(conn)

        # Vector store rows are recorded as their own storage entries.
        for name, cnt in (await milvus_counts()).items():
            if cnt <= 0:
                continue
            citable = name in ("legal_articles",)
            sources.append(CorpusSource(
                source_key=f"milvus_{name}",
                display_name=f"向量集合 {name}",
                storage="milvus",
                location=name,
                provenance="authoritative" if citable else "open_source",
                citable=citable,
                record_count=cnt,
                commercial_use="继承源数据集许可",
                note="用于语义检索；provenance 继承其来源表",
            ))

        # Persist
        await conn.execute("DELETE FROM corpus_registry")
        await conn.executemany(
            """
            INSERT INTO corpus_registry (source_key, display_name, storage, location,
                                         provenance, citable, record_count,
                                         commercial_use, note)
            VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9)
            """,
            [
                (s.source_key, s.display_name, s.storage, s.location, s.provenance,
                 s.citable, s.record_count, s.commercial_use, s.note)
                for s in sources
            ],
        )

        # ---------------- report ----------------
        citable = [s for s in sources if s.citable and s.record_count > 0]
        non_citable = [s for s in sources if not s.citable and s.record_count > 0]
        citable_total = sum(s.record_count for s in citable)
        synthetic_total = sum(s.record_count for s in sources if s.provenance == "synthetic" and s.record_count > 0)

        print("=" * 86)
        print("法律语料治理审计 (corpus provenance audit)")
        print("=" * 86)
        print(f"{'来源':40s} {'类型':14s} {'可引用':6s} {'记录数':>14s}")
        print("-" * 86)
        for s in sorted(sources, key=lambda x: -x.record_count):
            if s.record_count < 0:
                continue
            print(f"{s.display_name[:38]:40s} {s.provenance:14s} "
                  f"{'是' if s.citable else '否':6s} {s.record_count:>14,}")
        print("-" * 86)
        print(f"{'可引用（citation-grade）语料合计':40s} {'':14s} {'':6s} {citable_total:>14,}")
        print(f"{'不可引用语料合计':40s} {'':14s} {'':6s} {sum(s.record_count for s in non_citable):>14,}")
        print(f"{'其中合成数据（严禁展示）':40s} {'':14s} {'':6s} {max(synthetic_total,0):>14,}")
        print("=" * 86)
        print(f"目标 100,000,000 条可引用语料 → 当前完成度 "
              f"{citable_total / 100_000_000 * 100:.2f}%")

        if args.json_out:
            with open(args.json_out, "w", encoding="utf-8") as f:
                json.dump([asdict(s) for s in sources], f, ensure_ascii=False, indent=2)
            print(f"\nregistry written to {args.json_out}")

    finally:
        await conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
