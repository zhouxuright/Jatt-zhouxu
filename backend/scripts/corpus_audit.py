@dataclass
class CorpusSource:
    source_key: str
    display_name: str
    storage: str            # "postgres" | "milvus" | "local_file"
    location: str           # table / collection / path
    provenance: str         # "authoritative" | "open_source" | "synthetic"
    citable: bool           # may be shown to users as legal authority
    record_count: int
    commercial_use: str     # licence note
    note: str = ""


SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS corpus_registry (
    source_key      varchar(96)  PRIMARY KEY,
    display_name    varchar(256) NOT NULL,
    storage         varchar(32)  NOT NULL,
    location        varchar(256) NOT NULL,
    provenance      varchar(32)  NOT NULL,
    citable         boolean      NOT NULL,
    record_count    bigint       NOT NULL DEFAULT 0,
    commercial_use  varchar(256),
    note            text,
    measured_at     timestamptz  NOT NULL DEFAULT now()
);
"""


async def table_count(conn: asyncpg.Connection, table: str) -> int:
    try:
        return await conn.fetchval(f"SELECT count(*) FROM {table}")  # noqa: S608
    except Exception:  # noqa: BLE001
        return -1


