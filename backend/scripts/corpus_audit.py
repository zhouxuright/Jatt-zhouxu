"""Legal corpus audit & provenance registry.

Creates and refreshes a ``corpus_registry`` table that records, for every data
source in the system:

* how many records it actually contains (measured, not estimated),
* what its **provenance** is (authoritative / open-source / synthetic),
* whether it is **citable** to an end user as legal authority,
* and what licence governs commercial use.

Why this exists
---------------
A commercial legal AI lives or dies on citation integrity.  Mixing
template-generated synthetic records into the retrieval corpus is exactly how
products end up fabricating case numbers and getting sanctioned (700+ court
cases globally in 2026 involve AI-hallucinated citations).  The synthetic
corpus on disk (15M records) *must not* be presented as precedent.

This script makes that boundary explicit and machine-checkable, and gives a
defensible single source of truth for "how much legal data do we actually
have, and what may we legally use".

Usage (inside the backend container):

    python scripts/corpus_audit.py
    python scripts/corpus_audit.py --json out.json
"""
